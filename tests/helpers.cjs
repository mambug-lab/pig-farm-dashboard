const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');

function loadGs(overrides = {}) {
  const context = vm.createContext({Logger: {log() {}}, ...overrides});
  const files = fs.readdirSync(path.join(root, 'apps-script')).filter(f => f.endsWith('.gs')).sort();
  vm.runInContext(files.map(f => fs.readFileSync(path.join(root, 'apps-script', f), 'utf8')).join('\n'), context);
  context.TestDate = vm.runInContext('Date', context);
  return context;
}
const defaultRooms = [
  ['sow', 'Свиноматки', 'S1'], ['suckling', 'Поросята-сосуны', 'P1'],
  ['weaned', 'Отъем поросята', 'W1'], ['growing', 'Доращивание', 'G1'],
  ['fattening_old', 'Откорм ст', 'F1'], ['fattening_new', 'Откорм нов', 'F2']
];
function makeMonth(c, year, month, days, options = {}) {
  const rooms = options.rooms || defaultRooms;
  const stock = Object.fromEntries(rooms.map(r => [r[2], options.opening?.[r[2]] ?? 100]));
  const values = [], formulas = [], blocks = [];
  const add = (row, formula = Array(10).fill('')) => { values.push(row); formulas.push(formula); };
  for (const spec of days) {
    const date = new c.TestDate(year, month - 1, spec.day, 12);
    const start = values.length + 1;
    add([date, ...Array(9).fill('')]);
    add(['Отделение', '', '', 'Предыдущий день', 'Завоз', 'Вывоз', 'Погибшие', 'Продажа', 'Итого', 'Факт']);
    const totals = Array(6).fill(0);
    for (const [, section, room] of rooms) {
      const moves = spec.moves?.[room] || [0, 0, 0, 0];
      const opening = stock[room], closing = opening + moves[0] - moves[1] - moves[2] - moves[3];
      const row = [section, '', room, opening, ...moves, closing, spec.audits?.[room] ?? ''];
      const formula = Array(10).fill(''); formula[8] = '=D+E-F-G-H';
      add(row, formula);
      for (let i = 0; i < 6; i++) totals[i] += row[i + 3];
      stock[room] = closing;
    }
    add(['ВСЕГО', '', '', ...totals, spec.totalAudit ?? '']);
    blocks.push({date, dateBlockStartRow: start, copyEndRow: values.length,
      nextDateRow: values.length + 1, inputAnchorCount: spec.unconfirmed ? 0 : 4,
      hasValidInput: !spec.template, matchedAnchorCount: 4});
  }
  const displayValues = values.map(row => row.map(v => v instanceof c.TestDate
    ? `${v.getFullYear()}-${String(v.getMonth()+1).padStart(2,'0')}-${String(v.getDate()).padStart(2,'0')}` : String(v)));
  const valid = blocks.filter(b => b.hasValidInput);
  return {year, monthIndex: month, sheetName: `${year}-${month}`, autoGenerated: !!options.autoGenerated,
    sheet: {getSheetId: () => year * 100 + month},
    scan: {lastRow: values.length, values, displayValues, formulas}, allBlocks: blocks, validBlocks: valid,
    validCount: valid.length, hasValidInput: !!valid.length,
    latestDate: valid.at(-1)?.date, copyEndRow: valid.at(-1)?.copyEndRow};
}
function openingAudit(c, info, amounts = {}) {
  const first = info.allBlocks[0].date;
  return {canApply: true, date: new c.TestDate(first.getFullYear(), first.getMonth(), first.getDate()-1,12),
    groupValues: Object.fromEntries(defaultRooms.map(r => [r[0], amounts[r[0]] ?? 100]))};
}
function process(c, infos, records = []) {
  c.matchGroupInventoryAuditsToBlocks_(infos, records);
  c.applyInventoryAuditAdjustments_(infos);
  c.applyGroupInventoryAuditAdjustments_(infos, records);
  return infos;
}
module.exports = {loadGs, makeMonth, openingAudit, process, defaultRooms, root};
